"""Ad hoc: quantifies how "distinctive" the HDBSCAN clusters found by
`*_small_table_hdbscan.py` actually are, for two runs side by side:
`distill-gpt-to-baseline` (dim_in=8, latest) vs. `gpu-retriver-tokenid`
(dim_in=8, latest) -- the two richest-looking clusterings found so far.

More clusters is not automatically "more distinctive": a cluster could be
loosely scattered (low intra-cluster cosine similarity) or sit right next to
a neighboring cluster's centroid (low inter-cluster separation), in which
case the cluster boundary is somewhat arbitrary rather than a real geometric
gap. This script computes, per run, using the *already-cached* HDBSCAN
labels (no reclustering):

  - mean intra-cluster cosine similarity (tightness): for each cluster,
    average pairwise cosine similarity among its member embeddings. Higher =
    members are genuinely close together, not loosely lumped.
  - mean inter-cluster centroid cosine similarity (separation): average
    pairwise cosine similarity between different clusters' centroids. Lower
    = clusters sit further apart from each other on the sphere.
  - a combined "distinctiveness" score = intra-cluster tightness minus
    inter-cluster centroid similarity (higher is better: tight clusters that
    are also far from their neighbors).

Requires the two runs' HDBSCAN label caches to already exist under
`results/` (generated by `distill_gpt_to_baseline_small_table_hdbscan.py`
and `gpu_retriver_tokenid_small_table_hdbscan.py`).

Usage:
    .venv/bin/python ad_hoc_scripts/small_table_cluster_distinctiveness.py
"""

from pathlib import Path

import numpy as np

from model.device import setup_backend

setup_backend()

from keras import ops  # noqa: E402

from model.scripts._model_io import load_dual_embedding_tables  # noqa: E402

OUT_DIR = Path(__file__).resolve().parent / "results"

RUNS = {
    "distill-gpt-to-baseline": {
        "checkpoint": "latest",
        "labels_path": OUT_DIR / "distill_gpt_to_baseline_small_table_hdbscan_labels.npy",
    },
    "gpu-retriver-tokenid": {
        "checkpoint": "latest",
        "labels_path": OUT_DIR / "gpu_retriver_tokenid_small_table_hdbscan_labels.npy",
    },
}


def _mean_pairwise_cosine(points: np.ndarray) -> float:
    """Mean pairwise cosine similarity among rows of `points` (already unit-norm).

    O(n^2) via a single matmul -- fine at cluster sizes up to a few hundred;
    the two biggest clusters found so far are excluded by the caller's
    own filtering if they get too large to be a meaningful "tightness" read.
    """
    if len(points) < 2:
        return 1.0
    sims = points @ points.T
    n = len(points)
    # Exclude the diagonal (self-similarity == 1.0, which would inflate the mean).
    total = sims.sum() - n
    count = n * (n - 1)
    return float(total / count) if count else 1.0


def main() -> int:
    for run_name, cfg in RUNS.items():
        small_table, _big_table, _config, _ckpt_path = load_dual_embedding_tables(run_name, cfg["checkpoint"])
        points = ops.convert_to_numpy(small_table).astype(np.float64)

        labels = np.load(cfg["labels_path"])
        unique = sorted(set(labels[labels >= 0].tolist()))

        intra_scores = []
        centroids = []
        cluster_sizes = []
        for c in unique:
            members = points[labels == c]
            cluster_sizes.append(len(members))
            # Skip pathologically large "clusters" (a near-total-collapse blob)
            # for the tightness computation -- a 2000+-member blob's average
            # pairwise similarity isn't a meaningful "is this cluster tight"
            # signal the way it is for a real, size ~10-150 semantic cluster;
            # it's reported separately instead.
            if len(members) <= 300:
                intra_scores.append(_mean_pairwise_cosine(members))
            centroid = members.mean(axis=0)
            centroid = centroid / np.linalg.norm(centroid)
            centroids.append(centroid)

        centroids = np.array(centroids)
        inter_sim = _mean_pairwise_cosine(centroids) if len(centroids) > 1 else 0.0

        mean_intra = float(np.mean(intra_scores)) if intra_scores else float("nan")
        distinctiveness = mean_intra - inter_sim

        large_clusters = [s for s in cluster_sizes if s > 300]

        print(f"\n=== {run_name} ===")
        print(f"  clusters (excluding blobs >300 members from tightness calc): {len(intra_scores)}/{len(unique)}")
        print(f"  large 'blob' clusters (>300 members): {large_clusters}")
        print(f"  mean intra-cluster cosine similarity (tightness):   {mean_intra:.4f}")
        print(f"  mean inter-cluster centroid cosine similarity (overlap): {inter_sim:.4f}")
        print(f"  distinctiveness score (tightness - overlap):        {distinctiveness:.4f}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
