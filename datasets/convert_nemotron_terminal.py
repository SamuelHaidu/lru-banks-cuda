"""Converts nvidia/Nemotron-Terminal-Corpus (skill_based easy: Terminus-2 agent trajectories in a Linux terminal,
generated by DeepSeek-V3.2) to our conversation format (`datasets/build_agent_mix_bpe.py` tags).

    <bos><system>You are an AI assistant tasked with solving command-line tasks ...</system><tools>
    terminal(keystrokes: str, duration: float): ...
    task_complete(): ...
    </tools><user>## Task title ... Current terminal state: ...</user>
    <assistant><think>...</think>analysis\n\nplan<call>terminal(keystrokes="ls -la\\n", duration=0.1)</call>...</assistant>
    <result>terminal screen after the batch</result> ... <assistant>...<call>task_complete()</call></assistant>
    <result>... Are you sure ...? If so, call task_complete() again.</result><assistant>...</assistant><eos>

Source -> ours: the first user message is the fixed instructions (first paragraph -> <system>; the JSON response
format, which no longer applies, dropped) + the task and the starting screen (-> <user>). Each assistant message
`<think>...</think>{"analysis", "plan", "commands": [{"keystrokes", "duration"}], "task_complete"}` -> <think>, the
analysis and plan as text, a terminal(...) call per command (keystrokes verbatim, a JSON string), task_complete()
if set. Every later user message is the harness (the screen after a batch) -> <result>.
Dropped: trajectories with an assistant message that has no valid JSON (59%: the model only thought; the harness
answered "parsing errors" and the next thoughts discuss the JSON format, which no longer exists after conversion),
with harness warnings, or with one of our tags in the source text.

    uv run --with pyarrow python datasets/convert_nemotron_terminal.py --samples 1
    uv run --with pyarrow python datasets/convert_nemotron_terminal.py    # -> datasets/raw/nemotron-terminal/easy_converted.jsonl
"""

from __future__ import annotations

import argparse
import collections
import json
import re
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path
from typing import Dict, List, Optional, Tuple

HERE = Path(__file__).resolve().parent
RAW = HERE / "raw" / "nemotron-terminal" / "easy"
OUT = HERE / "raw" / "nemotron-terminal" / "easy_converted.jsonl"
SPECIAL = ["<bos>", "<eos>", "<tools>", "</tools>", "<user>", "</user>", "<assistant>", "</assistant>", "<call>",
           "</call>", "<result>", "</result>", "<system>", "</system>", "<think>", "</think>"]
_TAG = re.compile("|".join(re.escape(t) for t in SPECIAL))
TOOLS = ("<tools>\n"
         "terminal(keystrokes: str, duration: float): send keystrokes to the terminal verbatim (end a command with \\n; "
         "C-c, C-d for Ctrl+C, Ctrl+D), wait duration seconds, return the screen\n"
         "task_complete(): mark the task as complete (it is then graded)\n"
         "</tools>")
CONFIRM_SRC = 'If so, include "task_complete": true in your JSON response again.'
CONFIRM_OUT = "If so, call task_complete() again."


def _assistant(content: str) -> Optional[Tuple[str, bool]]:
    """An assistant message -> (the inside of <assistant>, task_complete), None if it has no valid JSON."""
    think, sep, rest = content.partition("</think>")
    if not sep:
        return None
    try:
        j = json.loads(rest.strip())
    except json.JSONDecodeError:
        return None
    if not isinstance(j, dict) or not isinstance(j.get("commands", []), list):
        return None
    think = think.strip()
    think = think[len("<think>"):].strip() if think.startswith("<think>") else think
    text = "\n\n".join(s.strip() for s in (j.get("analysis") or "", j.get("plan") or "") if s and s.strip())
    calls = []
    for c in j.get("commands") or []:
        if not isinstance(c, dict) or "keystrokes" not in c:
            return None
        args = {"keystrokes": c["keystrokes"], **({"duration": c["duration"]} if "duration" in c else {})}
        calls.append("<call>terminal(" + ", ".join(f"{k}={json.dumps(v, ensure_ascii=False)}" for k, v in args.items())
                     + ")</call>")
    done = bool(j.get("task_complete"))
    if done:
        calls.append("<call>task_complete()</call>")
    return f"<think>{think}</think>{text}" + "".join(calls), done


def _result(content: str) -> Optional[str]:
    """A harness message -> the inside of <result> (None: not a terminal screen)."""
    c = content
    if c.startswith("Current terminal state:\n"):  # the confirmation after task_complete
        c = c[len("Current terminal state:\n"):]
        if CONFIRM_SRC not in c:
            return None
        c = c.replace(CONFIRM_SRC, CONFIRM_OUT)
    for head in ("New Terminal Output:\n", "Current Terminal Screen:\n"):
        if c.startswith(head):
            return c[len(head):].strip("\n")
    return None


def convert(row: Dict, stats: collections.Counter) -> Optional[str]:
    cv = row["conversations"]
    first = cv[0]["content"] if cv and cv[0]["role"] == "user" else ""
    head, sep, task = first.partition("Task Description:\n")
    if not sep:
        stats["skip: no task description"] += 1
        return None
    # (an assistant message's own <think> ... </think> wrapper becomes our tags; any other tag in the text is foreign)
    own = lambda m: m["content"].replace("<think>", "", 1).replace("</think>", "", 1) if m["role"] == "assistant" else m["content"]
    if any(_TAG.search(own(m)) for m in cv):
        stats["skip: source contains one of our tags"] += 1
        return None
    parts = ["<bos>", f"<system>{head.split(chr(10) + chr(10))[0].strip()}</system>", TOOLS, f"<user>{task.strip()}</user>"]
    for m in cv[1:]:
        if m["role"] == "assistant":
            a = _assistant(m["content"])
            if a is None:
                stats["skip: an assistant message without valid JSON"] += 1
                return None
            parts.append(f"<assistant>{a[0]}</assistant>")
        elif m["role"] == "user":
            r = _result(m["content"])
            if r is None:
                stats["skip: harness message " + repr(m["content"][:30])] += 1
                return None
            parts.append(f"<result>{r}</result>")
        else:
            stats[f"skip: role {m['role']}"] += 1
            return None
    parts.append("<eos>")
    return "".join(parts)


def convert_file(path: Path) -> Tuple[List[Dict], collections.Counter]:
    import pyarrow.parquet as pq

    stats, out = collections.Counter(), []
    f = pq.ParquetFile(path)
    for g in range(f.num_row_groups):
        for row in f.read_row_group(g, columns=["conversations", "task"]).to_pylist():
            stats["rows"] += 1
            doc = convert(row, stats)
            if doc is not None:
                stats["kept"] += 1
                out.append({"text": doc, "skill": path.stem, "task": row["task"]})
    return out, stats


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--samples", type=int, default=0, help="print this many converted documents and exit")
    a = p.parse_args()
    files = sorted(RAW.glob("*.parquet"))
    if a.samples:
        docs, stats = convert_file(files[0])
        for d in docs[: a.samples]:
            print(d["text"][:6000], f"\n... [{len(d['text'])} chars]\n" + "-" * 100)
        print(dict(stats))
        return
    total, n_bytes = collections.Counter(), []
    with ProcessPoolExecutor(min(len(files), 4)) as ex, open(OUT, "w") as out:
        for docs, stats in ex.map(convert_file, files):
            total += stats
            for d in docs:
                out.write(json.dumps(d, ensure_ascii=False) + "\n")
                n_bytes.append(len(_TAG.sub("\x00", d["text"]).encode("utf-8")))  # a tag counts 1
            print(docs[0]["skill"] if docs else "?", dict(stats))
    n_bytes.sort()
    q = lambda f: n_bytes[min(len(n_bytes) - 1, int(f * len(n_bytes)))]
    print(f"Wrote {OUT}: {total['kept']:,} of {total['rows']:,} trajectories, {sum(n_bytes) / 1e6:.0f} MB; "
          f"bytes per document p50 {q(0.5):,} p90 {q(0.9):,} p99 {q(0.99):,} max {n_bytes[-1]:,}")
    print({k: v for k, v in total.items() if k.startswith("skip")})


if __name__ == "__main__":
    main()
